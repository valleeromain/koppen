        const modalIntro = document.getElementById('introModal');
        const modalKoppen = document.getElementById('customKoppenModal');
        const modalFeedback = document.getElementById('customFeedbackModal');
        
        // Sécurité : Fonctions globales pour ouvrir les modales depuis l'extérieur
        window.ouvrirModalIntro = () => modalIntro?.classList.add('active');
        window.ouvrirModalKoppen = () => modalKoppen?.classList.add('active');
        window.ouvrirModalFeedback = () => modalFeedback?.classList.add('active');

        // === 3. GESTION DU FEEDBACK (Étoiles) ===
        let customSelectedRating = 0;
        const stars = document.querySelectorAll('.custom-star');
        stars.forEach(star => {
            star.addEventListener('click', function() {
                customSelectedRating = parseInt(this.dataset.rating);
                stars.forEach((s, index) => {
                    s.classList.toggle('active', index < customSelectedRating);
                });
            });
            
            // Support tactile
            star.addEventListener('touchstart', function(e) {
                e.preventDefault();
                customSelectedRating = parseInt(this.dataset.rating);
                stars.forEach((s, index) => {
                    s.classList.toggle('active', index < customSelectedRating);
                });
            });
        });

        // === 4. LOGIQUE D'AFFICHAGE AUTO (Intro & Notification) ===
        if (modalIntro) {
            setTimeout(() => modalIntro.classList.add('active'), 800);
        }

        // Notification Feedback après 20s
        let notificationTimeout;
        function scheduleNotification() {
            notificationTimeout = setTimeout(() => {
                if (!localStorage.getItem('customFeedbackSubmitted') && !localStorage.getItem('feedbackDismissed')) {
                    showFeedbackNotification();
                }
            }, 20000);
        }
        
        scheduleNotification();

        function showFeedbackNotification() {
            if (document.querySelector('.feedback-notification')) return;
            
            const notification = document.createElement('div');
            notification.className = 'feedback-notification';
            notification.setAttribute('role', 'alert');
            notification.innerHTML = `
                <div style="background: linear-gradient(135deg, #1a2a3a, #0f1a24); border: 1px solid rgba(59, 130, 246, 0.3); border-radius: 16px; padding: 12px 16px; display: flex; align-items: center; gap: 12px; box-shadow: 0 10px 25px rgba(0,0,0,0.3); backdrop-filter: blur(10px);">
                    <span style="font-size: 24px;">&#128172;</span>
                    <div style="flex: 1;">
                        <strong style="color: #fbbf24; display: block; font-size: 13px;">Votre avis compte !</strong>
                        <small style="color: #94a3b8; font-size: 11px;">Partagez votre exp&eacute;rience</small>
                    </div>
                    <button id="openFeedbackNotifBtn" style="background: #3b82f6; border: none; padding: 8px 14px; border-radius: 8px; color: white; cursor: pointer; font-size: 12px; font-weight: bold;">&#9733; Noter</button>
                    <button id="closeFeedbackNotifBtn" style="background: none; border: none; color: #64748b; cursor: pointer; font-size: 20px; padding: 5px;">&#10005;</button>
                </div>
            `;
            notification.style.cssText = "position: fixed; bottom: 100px; right: 20px; z-index: 10001; animation: slideUp 0.3s ease-out; max-width: 350px;";
            document.body.appendChild(notification);

            const openBtn = document.getElementById('openFeedbackNotifBtn');
            const closeBtn = document.getElementById('closeFeedbackNotifBtn');
            
            if (openBtn) {
                openBtn.onclick = () => {
                    modalFeedback?.classList.add('active');
                    notification.remove();
                    if (notificationTimeout) clearTimeout(notificationTimeout);
                };
            }
            
            if (closeBtn) {
                closeBtn.onclick = () => {
                    notification.remove();
                    localStorage.setItem('feedbackDismissed', 'true');
                    if (notificationTimeout) clearTimeout(notificationTimeout);
                };
            }
        }

        // === 5. SYSTÈME DE FERMETURE (Multi-modal) ===
        const closeAllModals = () => {
            document.querySelectorAll('.custom-modal').forEach(m => m.classList.remove('active'));
        };

        document.addEventListener('click', (e) => {
            if (e.target.closest('.custom-close-btn') || 
                e.target.id === 'startBtn' || 
                e.target.id === 'closeKoppenBtn' || 
                e.target.id === 'skipFeedbackBtn' || 
                e.target.id === 'closeFeedbackBtn') {
                closeAllModals();
            }
            
            if (e.target.id === 'learnMoreBtn') {
                modalIntro?.classList.remove('active');
                modalKoppen?.classList.add('active');
            }

            if (e.target.classList.contains('custom-modal')) {
                e.target.classList.remove('active');
            }
        });

        document.addEventListener('keydown', (e) => {
            if (e.key === 'Escape') {
                closeAllModals();
            }
        });

