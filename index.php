        const submitBtn = document.getElementById('submitFeedbackBtn');
        if (submitBtn) {
            submitBtn.addEventListener('click', () => {
                const comment = document.getElementById('customCommentText')?.value || '';
                
                if (customSelectedRating === 0) {
