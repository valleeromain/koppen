                    return;
                }
                
                fetch('api_feedback.php', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({
                        rating: customSelectedRating,
                        comment: comment,
                        page: window.location.pathname,
                        timestamp: new Date().toISOString()
                    })
                })
                .then(() => {
                    modalFeedback?.classList.remove('active');
                    localStorage.setItem('customFeedbackSubmitted', 'true');
                    alert('Merci pour votre retour ! &#128591;');
                    customSelectedRating = 0;
                    stars.forEach(s => s.classList.remove('active'));
                    if (document.getElementById('customCommentText')) {
                        document.getElementById('customCommentText').value = '';
                    }
                })
                .catch(err => {
                    console.error('Erreur:', err);
                    alert('Une erreur est survenue. Merci de r&#233;essayer plus tard.');
                });
